"""Integrated Host/Manager/Runner entry point; scanner service is mandatory.

The installer renders a dedicated MCP configuration with this entry point. No
scanner-selection flag is needed and there is no fallback to a local scanner.
"""
from __future__ import annotations

import argparse
import asyncio
import json
import os
from pathlib import Path
import sys

REPO = Path(__file__).resolve().parents[1]
if str(REPO) not in sys.path:
    sys.path.insert(0, str(REPO))


def host_arguments(runner: Path, work: Path, state: Path) -> list[str]:
    return [
        "--runner-exe", str(runner), "--sandbox-root", str(state / "sandbox"),
        "--inbox", str(work / "inbox"), "--shared", str(work / "shared"),
        "--save-downloads", "--agent-guard", "--artifact-export",
        "--artifact-scanner", "defender-service", "--approval", "dialog",
        "--sandbox-run", "--router-capture",
        "--artifact-dir", str(state / "artifacts"), "--export-dir", str(state / "exports"),
        "--cert-dir", str(state / "certs"), "--audit-dir", str(state / "audit"),
        "--log-file", str(state / "host.log"), "--startup-timeout", "180",
    ]


def validate_paths(runner: Path, work: Path, state: Path) -> None:
    """Validate before ACL changes, including ancestors that resolve through links."""
    from sandbox_manager.inbox import USER_FOLDERS
    for path in (runner, work, state):
        if not path.is_absolute() or path != path.resolve():
            raise ValueError(f"use an absolute path without links or '..': {path}")
    if not runner.is_file():
        raise ValueError(f"Runner executable does not exist: {runner}")
    home = Path.home().resolve()
    forbidden = [home / name for name in USER_FOLDERS]
    forbidden += [Path(os.environ[v]).resolve() for v in
                  ("OneDrive", "OneDriveCommercial", "OneDriveConsumer") if os.environ.get(v)]
    if work == Path(work.anchor) or home.is_relative_to(work):
        raise ValueError("work must not contain the user profile or be a drive root")
    if any(work.is_relative_to(p) or p.is_relative_to(work) for p in forbidden):
        raise ValueError("work must be separate from user folders and OneDrive")
    for path in (state, REPO, runner, Path(sys.executable).resolve()):
        if path.is_relative_to(work) or work.is_relative_to(path):
            raise ValueError(f"work must be separate from application/state files: {path}")


async def check_service(state: Path) -> None:
    from host.artifact_scan import DefenderServiceScanner
    from host.shared_scanner import ServiceSharedFinisher
    finish = ServiceSharedFinisher()
    await finish.check_available()
    ok, why = await DefenderServiceScanner(client=finish.client).refresh(state / "exports")
    if not ok:
        raise RuntimeError(why)


def render_config(runner: Path, work: Path, state: Path) -> str:
    # JSON strings/arrays are also TOML basic strings/arrays, with these path values.
    quote = lambda value: json.dumps(str(value), ensure_ascii=False)
    args = [str(REPO / "host" / "solution.py"), "--runner-exe", str(runner),
            "--work", str(work), "--state", str(state)]
    return ("# Generated by installer/install_solution.ps1. Run as the ordinary Host user.\n"
            "[mcp_servers.scrp_sandbox]\n"
            f"command = {quote(sys.executable)}\n"
            f"args = {json.dumps(args, ensure_ascii=False)}\n"
            f"cwd = {quote(REPO)}\n"
            "enabled = true\nstartup_timeout_sec = 60\ntool_timeout_sec = 120\n"
            "default_tools_approval_mode = \"approve\"\n"
            "\n[mcp_servers.scrp_sandbox.env]\nPYTHONIOENCODING = \"utf-8\"\n"
            "PYTHONDONTWRITEBYTECODE = \"1\"\n")


def main(argv=None):
    p = argparse.ArgumentParser(description=__doc__)
    source = p.add_mutually_exclusive_group(required=True)
    source.add_argument("--runner-exe", type=Path)
    source.add_argument("--config", type=Path)
    p.add_argument("--work", type=Path, default=Path.home() / "SecureCUA" / "solution")
    p.add_argument("--state", type=Path, default=Path.home() / "SecureCUAState" / "solution")
    mode = p.add_mutually_exclusive_group()
    mode.add_argument("--validate-paths", action="store_true")
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--write-config", type=Path)
    mode.add_argument("--register-codex", type=Path)
    a = p.parse_args(argv)
    try:
        profile = None
        if a.config:
            from host.solution_config import read_profile
            a.config = a.config.resolve()
            profile = read_profile(a.config)
            if Path(profile['host_repo']).resolve() != REPO:
                raise ValueError('profile belongs to a different Host checkout')
            a.runner_exe = Path(profile['runner_exe'])
            a.work, a.state = Path(profile['work']), Path(profile['state'])
        validate_paths(a.runner_exe, a.work, a.state)
        if a.validate_paths:
            return
        from sandbox_manager.inbox import check_inbox_root
        from host.inbox_download import check_no_execute
        for path in (a.work / "inbox", a.work / "shared"):
            check_inbox_root(path)
            ok, why = check_no_execute(path)
            if not ok:
                raise RuntimeError(f"{path}: {why}")
        asyncio.run(check_service(a.state))
        if a.register_codex:
            if not profile:
                raise ValueError('--register-codex requires --config')
            from host.solution_config import register_mcp, render_profile_mcp
            backup = register_mcp(a.register_codex, render_profile_mcp(a.config, profile))
            print(f'CODEX_REGISTERED: {a.register_codex}; backup={backup or "unchanged"}; reconnect MCP')
            return
        if a.write_config:
            a.write_config.parent.mkdir(parents=True, exist_ok=True)
            temp = a.write_config.with_suffix(".tmp")
            if profile:
                from host.solution_config import render_profile_mcp
                rendered = render_profile_mcp(a.config, profile)
            else:
                rendered = render_config(a.runner_exe, a.work, a.state)
            temp.write_text(rendered, encoding="utf-8")
            temp.replace(a.write_config)
            return
        if a.check:
            print("SOLUTION_READY: Shared + artifact scanner service, Defender and deny-execute folders checked")
            return
    except Exception as e:
        p.exit(1, f"SOLUTION_NOT_READY: {e}\n")
    from host.mcp_server import main as run_host
    run_host(host_arguments(a.runner_exe, a.work, a.state))


if __name__ == "__main__":
    main()
